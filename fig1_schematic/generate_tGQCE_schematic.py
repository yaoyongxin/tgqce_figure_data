def text(x,y,t,size=23,color=ink,anchor='start',weight='normal'):
    S.append(f'<text x="{x}" y="{y}" font-size="{size}" fill="{color}" style="fill:{color}" text-anchor="{anchor}" font-weight="{weight}">{escape(t)}</text>')
def line(x1,y1,x2,y2,c=gray,w=2,extra=''):
    S.append(f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{c}" stroke-width="{w}" {extra}/>')
def path(d,c,w=3,fill='none',extra=''):
    S.append(f'<path d="{d}" fill="{fill}" stroke="{c}" stroke-width="{w}" {extra}/>')
def circle(x,y,r,fill,stroke,w=2):
    S.append(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{w}"/>')
def rect(x,y,w,h,fill,stroke='none',rx=0,sw=1):
    S.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>')
num=0
def math(x,y,expr,size=23,anchor='middle',color=ink):
    global num
    num+=1
    buf=io.BytesIO(); math_to_image('$'+expr+'$',buf,prop=FontProperties(size=size),format='svg',color=color)
    st=buf.getvalue().decode(); root=ET.fromstring(st)
    for parent in root.iter():
        for child in list(parent):
            if child.get('id')=='patch_1':parent.remove(child)
    width=float(root.attrib['width'].replace('pt','')); height=float(root.attrib['height'].replace('pt',''))
    root.set('x',str(x-width/2 if anchor=='middle' else x));root.set('y',str(y-height/2));root.set('width',str(width));root.set('height',str(height))
    for e in root.iter():
        if 'id' in e.attrib:e.set('id',f'm{num}_'+e.attrib['id'])
        for k,v in list(e.attrib.items()):
            if k.endswith('href') and v.startswith('#'): e.set(k,f'#m{num}_'+v[1:])
            elif 'url(#' in v:e.set(k,v.replace('url(#',f'url(#m{num}_'))
    S.append(ET.tostring(root,encoding='unicode'))

