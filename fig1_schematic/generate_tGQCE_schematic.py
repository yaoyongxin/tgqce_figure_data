"""Generate the revised time-dependent GQCE schematic as a vector SVG.

Requirements:
    python -m pip install matplotlib

Usage:
    python generate_tGQCE_schematic.py
    python generate_tGQCE_schematic.py --output my_figure.svg
    python generate_tGQCE_schematic.py --output my_figure.svg --png

The optional --png preview requires Inkscape on PATH. SVG generation itself
requires only Matplotlib and the Python standard library; LaTeX is not needed.

Text and geometric shapes are SVG elements; mathematical labels are vector
paths generated by Matplotlib MathText. Edit the drawing calls below to change
labels, positions, colors, equations, or lattice geometry. Coordinates refer to
the original 1500-unit drawing canvas. The viewBox crops the unused title area.
"""
